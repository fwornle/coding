// glass job-classes: the corpus read from the agents' own transcripts, and the
// measurement over it (lib/job-classes/prompts.mjs, lib/glass/job-classes-cli.mjs).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { collectPrompts } = await import('../lib/job-classes/prompts.mjs');
const { measure } = await import('../lib/glass/job-classes-cli.mjs');
const { loadTaxonomy } = await import('../proxy/proxy-bridge/job-class.mjs');

const tmp = () => fs.mkdtempSync(path.join(os.tmpdir(), 'glass-jc-'));
const ts = (minAgo) => new Date(Date.now() - minAgo * 60_000).toISOString();
const jsonl = (file, rows) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, rows.map((r) => JSON.stringify(r)).join('\n')); };

test('collectPrompts: what a person typed, interactively, from claude and copilot transcripts', () => {
  const claudeDir = tmp(); const copilotDir = tmp();
  const user = (content, extra = {}) => ({ type: 'user', entrypoint: 'cli', sessionId: 's1', cwd: '/w/shop', timestamp: ts(5), message: { role: 'user', content }, ...extra });
  jsonl(path.join(claudeDir, '-w-shop', 's1.jsonl'), [
    user('The checkout test fails since this morning, find out why.'),
    user('The checkout test fails since this morning, find out why.'), // repeated in the session
    user([{ type: 'tool_result', tool_use_id: 't', content: 'output' }]),
    user('<command-name>/clear</command-name>'),
    user('yes'),
    user('Run the nightly report again for all regions please', { entrypoint: 'sdk-cli' }), // claude -p
    user('A sub-agent prompt that a person never typed here', { isSidechain: true }),
    user('Caveat: the messages below were generated by the user', { isMeta: true }),
    { type: 'assistant', message: { content: 'ok' } },
  ]);
  jsonl(path.join(copilotDir, 'a1', 'events.jsonl'), [
    { type: 'session.start', data: { context: { cwd: '/w/api' } } },
    { type: 'user.message', timestamp: ts(3), data: { content: 'Add a CSV export to the orders endpoint.' } },
  ]);
  jsonl(path.join(copilotDir, 'a2', 'events.jsonl'), [
    { type: 'system.message', data: { content: 'You are running in non-interactive mode' } },
    { type: 'user.message', timestamp: ts(2), data: { content: 'Summarise the changes of this branch for the release notes.' } },
  ]);
  const { rows, counts } = collectPrompts({ claudeDir, copilotDir, vscodeDirs: [] });
  assert.deepEqual(rows.map((r) => [r.agent, r.repo, r.text]), [
    ['copilot', 'api', 'Add a CSV export to the orders endpoint.'],
    ['claude', 'shop', 'The checkout test fails since this morning, find out why.'],
  ]);
  assert.equal(counts.duplicate, 1);
  assert.equal(counts.noise, 1);
  assert.equal(counts.short, 1);
  assert.equal(new Set(rows.map((r) => r.id)).size, 2);
});

test('measure: teacher twice and the student once, redacted first, checkpointed, and the reference set written', async () => {
  const tax = loadTaxonomy(path.join(ROOT, 'config', 'job-classes.yaml'));
  const dir = tmp();
  const rows = [
    { id: 'a', ts: ts(1), agent: 'claude', repo: 'shop', text: 'Commit this and push, my key is SECRET-1' },
    { id: 'b', ts: ts(2), agent: 'claude', repo: 'shop', text: 'Why does the checkout test fail?' },
    { id: 'c', ts: ts(3), agent: 'copilot', repo: 'api', text: 'BLOCK this one' },
  ];
  const sent = [];
  const complete = async ({ process: proc, messages }) => {
    const text = messages[0].content;
    sent.push(text);
    // Only the request part: the taxonomy's own examples include "Commit this and push."
    const request = text.slice(text.lastIndexOf('REQUEST:'));
    const cls = request.includes('Commit this') ? 'ship' : proc === 'job-class-student' ? 'explain' : 'fix';
    return { content: `{"class":"${cls}"}`, model: 'm' };
  };
  const redact = (t) => (t.includes('BLOCK') ? '[REDACTION_ERROR_CONTENT_BLOCKED]' : t.replace(/SECRET-\d/g, '<SECRET_REDACTED>'));
  const r = await measure({ rows, tax, complete, dir, redact });
  assert.equal(r.n, 2, 'a prompt whose redaction failed is not sent');
  assert.equal(sent.length, 6);
  assert.ok(sent.every((t) => !t.includes('SECRET-1')));
  assert.equal(r.teacherSelfKappa, 1);
  assert.equal(r.studentAgree, 0.5);
  const ref = fs.readFileSync(r.reference.file, 'utf8').trim().split('\n').map((l) => JSON.parse(l));
  assert.deepEqual(ref.map((x) => [x.id, x.class, x.set]), [['a', 'ship', 'glass'], ['b', 'fix', 'glass']]);

  sent.length = 0;
  await measure({ rows, tax, complete, dir, redact });
  assert.equal(sent.length, 0, 'a rerun resumes from the checkpoints');
});

test('measure: an account that cannot answer stops the run with its reason', async () => {
  const tax = loadTaxonomy(path.join(ROOT, 'config', 'job-classes.yaml'));
  const complete = async () => { throw new Error('Copilot on github.com does not offer claude-sonnet-5 to this account'); };
  await assert.rejects(
    measure({ rows: [{ id: 'a', ts: ts(1), agent: 'claude', repo: 'x', text: 'Commit this and push.' }], tax, complete, dir: tmp() }),
    /does not offer claude-sonnet-5/,
  );
});
