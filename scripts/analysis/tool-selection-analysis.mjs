#!/usr/bin/env node
/**
 * Regenerates the data appendix behind docs/benchmarks/coding-v1/tool-selection.md.
 *
 * Every table on that page comes from here. Run it after any new kgbench run and the prose
 * can be checked against freshly derived numbers rather than remembered ones.
 *
 *   node scripts/analysis/tool-selection-analysis.mjs
 *   -> docs/benchmarks/coding-v1/analysis/tool-selection-data.md
 *
 * WHY THIS WRITES A FILE RATHER THAN PRINTING. These are wide fixed-width tables, and the
 * unified Logger prefixes every line with its level and category, which destroys column
 * alignment. Emitting markdown removes the need for terminal output entirely, and the result
 * is a reviewable artefact the report can link instead of an instruction to re-run something
 * and read the scrollback.
 *
 * THE ONE RULE THIS SCRIPT ENFORCES: a kgbench run is 3 reps x 16 questions, NOT 48
 * independent cells. Section 3 deliberately reports the cell-level test and the clustered
 * test side by side, because their disagreement is the finding.
 */

import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createLogger } from '../../lib/logging/Logger.js';
import {
  REPO_ROOT, loadRun, byQuestion, determinism, toolHistogram, cellUsedGraph, isGraphTool,
  fisherExact, mcnemarExact, median, mean, POOLED_RUNS, CURRENT_RUN, ALL_HYBRID_RUNS,
} from './tool-selection-lib.mjs';

const logger = createLogger('kgbench-analysis', { timestamp: false });
const ALL_RUNS = [...POOLED_RUNS, CURRENT_RUN];
const out = [];
const w = (s = '') => out.push(s);
const pct = (a, b) => (b ? `${(100 * a / b).toFixed(2)}%` : 'n/a');

w('# `tool-selection.md` — data appendix');
w();
w('Generated by `scripts/analysis/tool-selection-analysis.mjs`. Do not hand-edit.');
w();
w(`Runs analysed: ${ALL_RUNS.join(', ')}. Arm: \`hybrid\` unless stated.`);
w();

// ── 1. telemetry coverage ────────────────────────────────────────────────────
w('## 1. Tool telemetry by agent');
w();
w('A run with 0 recorded calls is not a run with no tool use — it is a run with no');
w('instrumentation. Every later section is therefore claude-only.');
w();
w('| run | agent | cells | recorded tool calls | `tool_audit` |');
w('|---|---|--:|--:|---|');
for (const run of [CURRENT_RUN, 'coding-v1-r8']) {
  for (const agent of ['claude', 'copilot', 'opencode']) {
    const rows = loadRun(run, { arm: 'hybrid', agent });
    if (!rows.length) continue;
    const calls = rows.reduce((s, r) => s + (r.tools_executed ?? []).length, 0);
    w(`| \`${run}\` | ${agent} | ${rows.length} | ${calls} | \`${rows[0].tool_audit ?? '(absent)'}\` |`);
  }
}
w();

// ── 2. uptake per run ────────────────────────────────────────────────────────
w('## 2. Graph uptake per run');
w();
w('`unanimous` counts questions whose reps all agree (all used a graph, or none did).');
w('It stays at 14–16 of 16 in every run: tool choice is a near-deterministic function of');
w('the question rather than a rate.');
w();
w('| run | tool calls | graph calls | rate | cells w/ graph | **questions** w/ graph | unanimous |');
w('|---|--:|--:|--:|--:|--:|--:|');
const perRun = new Map();
for (const run of ALL_RUNS) {
  const rows = loadRun(run, { arm: 'hybrid', agent: 'claude' });
  const calls = rows.reduce((s, r) => s + (r.tools_executed ?? []).length, 0);
  const graph = rows.reduce((s, r) => s + (r.tools_executed ?? []).filter(isGraphTool).length, 0);
  const q = byQuestion(rows);
  const qHit = [...q.values()].filter((v) => v.hits > 0).length;
  const d = determinism(rows);
  perRun.set(run, { qHit, qTotal: q.size });
  w(`| \`${run}\` | ${calls} | ${graph} | ${pct(graph, calls)} | `
    + `${rows.filter(cellUsedGraph).length}/${rows.length} | **${qHit}/${q.size}** | ${d.unanimous}/${d.total} |`);
}
w();

// ── 3. the test done both ways ───────────────────────────────────────────────
w('## 3. Did uptake really rise from `r8` to `r9`?');
w();
const A = loadRun('coding-v1-r8', { arm: 'hybrid', agent: 'claude' });
const B = loadRun(CURRENT_RUN, { arm: 'hybrid', agent: 'claude' });
const flat = (rows) => {
  const t = rows.flatMap((r) => r.tools_executed ?? []);
  return [t.filter(isGraphTool).length, t.length];
};
const [g8, n8] = flat(A); const [g9, n9] = flat(B);
const p1 = g8 / n8; const p2 = g9 / n9; const pp = (g8 + g9) / (n8 + n9);
const z = (p2 - p1) / Math.sqrt(pp * (1 - pp) * (1 / n8 + 1 / n9));
const erf = (x) => {
  const t = 1 / (1 + 0.3275911 * Math.abs(x));
  const y = 1 - ((((1.061405429 * t - 1.453152027) * t + 1.421413741) * t - 0.284496736) * t
    + 0.254829592) * t * Math.exp(-x * x);
  return x >= 0 ? y : -y;
};
const zp = 2 * (1 - 0.5 * (1 + erf(Math.abs(z) / Math.SQRT2)));
const qA = byQuestion(A); const qB = byQuestion(B);
let onlyA = 0; let onlyB = 0;
for (const id of new Set([...qA.keys(), ...qB.keys()])) {
  const x = (qA.get(id)?.hits ?? 0) > 0; const y = (qB.get(id)?.hits ?? 0) > 0;
  if (x && !y) onlyA += 1;
  if (!x && y) onlyB += 1;
}
const nq = perRun.get(CURRENT_RUN).qTotal;
const hitA = perRun.get('coding-v1-r8').qHit; const hitB = perRun.get(CURRENT_RUN).qHit;
w('| unit of analysis | comparison | test | p |');
w('|---|---|---|--:|');
w(`| 48 cells (as published) | ${g8}/${n8} vs ${g9}/${n9} | two-proportion z, z=${z.toFixed(3)} | ${zp.toExponential(2)} |`);
w(`| **16 questions** | ${hitA}/${nq} vs ${hitB}/${nq} | Fisher exact | **${fisherExact(hitB, nq - hitB, hitA, nq - hitA).toFixed(3)}** |`);
w(`| **16 questions, paired** | ${onlyB} gained, ${onlyA} lost | McNemar exact | **${mcnemarExact(onlyA, onlyB).toFixed(3)}** |`);
w();
w('The cell-level test treats 48 correlated cells as independent and overstates its own');
w('precision. Clustered on the question the shift is directionally clean — nothing lost the');
w('graph — but not resolvable at n=16.');
w();
w('### Per-question detail');
w();
w('| question | `r8` reps using a graph | `r9` reps using a graph |');
w('|---|--:|--:|');
for (const id of [...new Set([...qA.keys(), ...qB.keys()])].sort()) {
  const x = qA.get(id) ?? { hits: 0, reps: 0 }; const y = qB.get(id) ?? { hits: 0, reps: 0 };
  w(`| ${id} | ${x.hits}/${x.reps} | ${y.hits}/${y.reps} |`);
}
w();

// ── 4. when the choice is made ───────────────────────────────────────────────
w('## 4. When is the choice made?');
w();
w('First executed tool per cell. In both runs exactly one cell of 48 begins with text');
w('search and later reaches for a graph — the agent commits on turn 0 and does not revise.');
w();
for (const run of ['coding-v1-r8', CURRENT_RUN]) {
  const rows = loadRun(run, { arm: 'hybrid', agent: 'claude' });
  const first = new Map();
  let opened = 0; let late = 0;
  for (const r of rows) {
    const ex = r.tools_executed ?? [];
    if (!ex.length) continue;
    first.set(ex[0], (first.get(ex[0]) ?? 0) + 1);
    if (isGraphTool(ex[0])) opened += 1;
    else if (ex.some(isGraphTool)) late += 1;
  }
  w(`**\`${run}\`** — opened with a graph tool: **${opened}**; switched to one later: **${late}**`);
  w();
  w('| first tool | cells |');
  w('|---|--:|');
  for (const [t, c] of [...first.entries()].sort((a, b) => b[1] - a[1])) w(`| \`${t}\` | ${c} |`);
  w();
}

// ── 5. histogram ─────────────────────────────────────────────────────────────
w(`## 5. Executed-tool histogram — \`${CURRENT_RUN}\``);
w();
w('| tool | calls |');
w('|---|--:|');
for (const [t, c] of toolHistogram(B)) w(`| \`${t}\` | ${c} |`);
w();

// ── 6. cost, confounded and paired ───────────────────────────────────────────
w('## 6. Cost — the cross-cell comparison and the paired one');
w();
const G = B.filter(cellUsedGraph); const N = B.filter((r) => !cellUsedGraph(r));
w('Comparing cells directly appears to vindicate the preference decisively:');
w();
w('| cells | n | median content tokens | median cost | median score |');
w('|---|--:|--:|--:|--:|');
for (const [label, set] of [['used a graph tool', G], ['grep only', N]]) {
  w(`| ${label} | ${set.length} | ${Math.round(median(set.map((r) => r.content_tokens ?? 0)))} `
    + `| $${median(set.map((r) => r.cost_usd ?? 0)).toFixed(3)} | ${median(set.map((r) => r.score ?? 0)).toFixed(2)} |`);
}
w();
w('That comparison is confounded: the graph is called on a stable subset of questions, so');
w('this compares questions rather than strategies. The unconfounded version restricts to');
w('same-run, same-question pairs where some reps used a graph and some did not.');
w();
w('| run / question | graph reps, mean tokens | grep reps, mean tokens | ratio | graph score | grep score |');
w('|---|--:|--:|--:|--:|--:|');
const ratios = []; const deltas = []; const scoreDeltas = [];
for (const run of ALL_HYBRID_RUNS) {
  const rows = loadRun(run, { arm: 'hybrid', agent: 'claude' });
  const groups = new Map();
  for (const r of rows) {
    if (!groups.has(r.id)) groups.set(r.id, []);
    groups.get(r.id).push(r);
  }
  for (const [id, v] of [...groups.entries()].sort()) {
    const gg = v.filter(cellUsedGraph); const nn = v.filter((r) => !cellUsedGraph(r));
    if (!gg.length || !nn.length) continue;
    const gt = mean(gg.map((r) => r.content_tokens ?? 0));
    const nt = mean(nn.map((r) => r.content_tokens ?? 0));
    const gs = mean(gg.map((r) => r.score ?? 0)); const ns = mean(nn.map((r) => r.score ?? 0));
    ratios.push(gt / nt);
    deltas.push(mean(gg.map((r) => r.wall_s ?? 0)) - mean(nn.map((r) => r.wall_s ?? 0)));
    scoreDeltas.push(gs - ns);
    w(`| \`${run}\` / ${id} | ${Math.round(gt)} | ${Math.round(nt)} | ${(gt / nt).toFixed(2)}× `
      + `| ${gs.toFixed(2)} | ${ns.toFixed(2)} |`);
  }
}
w();
const nPairs = ratios.length;
const mRatio = mean(ratios);
const sdRatio = Math.sqrt(ratios.reduce((s2, x) => s2 + (x - mRatio) ** 2, 0) / (nPairs - 1));
const seRatio = sdRatio / Math.sqrt(nPairs);
const cheaper = ratios.filter((x) => x < 1).length;
const lfac = (k) => { let t = 0; for (let i = 2; i <= k; i += 1) t += Math.log(i); return t; };
const lch = (aa, bb) => lfac(aa) - lfac(bb) - lfac(aa - bb);
let tail = 0;
for (let k = Math.max(cheaper, nPairs - cheaper); k <= nPairs; k += 1) tail += Math.exp(lch(nPairs, k)) * 0.5 ** nPairs;
w(`Paired comparisons available: **${nPairs}**.`);
w();
w('| statistic | value |');
w('|---|--:|');
w(`| mean token ratio graph : grep | **${mRatio.toFixed(3)}×** |`);
w(`| 95% CI | **[${(mRatio - 1.96 * seRatio).toFixed(3)}, ${(mRatio + 1.96 * seRatio).toFixed(3)}]** |`);
w(`| graph cheaper in | ${cheaper}/${nPairs} pairs |`);
w(`| sign test, two-sided | p = ${Math.min(1, 2 * tail).toFixed(3)} |`);
w(`| mean score delta | ${mean(scoreDeltas).toFixed(3)} |`);
w();
w('**The interval spans 1.0 and the sign test is nowhere near significance.** Controlling for');
w('the question, the token difference between reaching for a graph and not reaching for one is');
w('indistinguishable from zero — the graph is neither reliably cheaper nor reliably dearer.');
w('That is the honest reading, and it supersedes an earlier n=8 pass of this same comparison');
w('which gave 0.81× and was written up as a reversal. Three more pairs moved the mean to');
w(`${mRatio.toFixed(2)}× and widened the interval across 1.0; a mean of eight ratios quoted`);
w('without dispersion read as a result it never was.');
w();
w('What survives is the negative half: the cross-cell table above is confounded by question');
w('difficulty and cannot support the claim that using a graph costs 2.29× more. That inference');
w('is retired. It is NOT replaced by the opposite one.');
w();

// ── 7. question shape ────────────────────────────────────────────────────────
//
// KEY_TOKEN is the one hand-maintained table in this script, and it has to be: the claim is
// "a token the QUESTION HANDS THE AGENT", which is a judgement about the prompt text, not
// something derivable from it. Each entry is asserted to appear verbatim in its own prompt,
// and the script FAILS rather than silently reporting on a token the prompt never contained.
const KEY_TOKEN = {
  // L3 and S1 are the two questions that do NOT hand over a bare identifier. L3's prompt
  // says "re-index" where the route is spelled `reindex`, so the greppable token is the
  // component name; S1 names no symbol at all, only the file its answer lives in. Both are
  // recorded here as what the prompt ACTUALLY offers, not as the token that would have
  // scored best — an earlier pass used `reindex`/`CODE_GRAPH_BACKEND` and was wrong.
  L1: 'MANAGED_MCP_KEYS', L2: 'summaryStats', L3: 'system-health',
  S1: 'config/code-graph.json', S2: 'supervisord', S3: 'transport',
  B1: 'mcp.tools', B2: '12435', B3: '.codegraph',
  A1: '.observations', A2: 'content tokens', A3: 'code-graph.json', A4: 'CodeGraph',
  T1: 'Memgraph', T3: 'payment reconciliation', T4: 'CODEGRAPH_MAX_DEPTH',
};

const questionsDoc = JSON.parse(fs.readFileSync(
  path.join(REPO_ROOT, 'config/kgbench/questions/coding-v1.json'), 'utf8',
));
const questions = (questionsDoc.questions ?? questionsDoc).filter((q) => q.enabled !== false);

w('## 7. Are the questions keyword-addressable?');
w();
w('For each question, a literal token appearing **verbatim in its own prompt** is searched');
w('across the repository and the hit set checked against that question\'s ground-truth');
w('evidence paths. `git grep -l` is used, so "rank" is path order, not relevance — the');
w('claim being tested is reachability, not ranking.');
w();
w('| question | token from the prompt | files hit | ground truth reachable |');
w('|---|---|--:|---|');
let reachable = 0; let gradeable = 0;
for (const q of questions) {
  const token = KEY_TOKEN[q.id];
  if (!token) throw new Error(`KEY_TOKEN has no entry for question ${q.id}`);
  if (!q.prompt.toLowerCase().includes(token.toLowerCase())) {
    throw new Error(`KEY_TOKEN["${q.id}"] = "${token}" does not appear in that question's prompt`);
  }
  let hits = [];
  try {
    hits = execFileSync('git', ['grep', '-l', '-F', '-i', '--', token], { cwd: REPO_ROOT, encoding: 'utf8' })
      .trim().split('\n').filter(Boolean);
  } catch { /* git grep exits 1 on no match */ }
  const evidence = [...new Set((q.provenance?.evidence ?? []).map((e) => e.split(':')[0]))];
  let verdict;
  if (!evidence.length) verdict = '— (abstain: nothing to find)';
  else {
    gradeable += 1;
    const found = evidence.some((f) => hits.includes(f));
    if (found) reachable += 1;
    verdict = found ? '**yes**' : 'no';
  }
  w(`| ${q.id} | \`${token}\` | ${hits.length} | ${verdict} |`);
}
w();
w(`**${reachable} of ${gradeable}** gradeable non-abstain questions have their ground truth in`);
w('the hit set of a single literal grep of a token the question hands the agent. This is a');
w('benchmark of keyword-addressable retrieval, and grep is the optimal instrument for that.');
w();

// ── 8. index coverage, and whether it drives the choice ──────────────────────
w('## 8. Is the answer even in the index?');
w();
const graphPath = path.join(REPO_ROOT, '.data/graphify/graphify-out/graph.json');
if (!fs.existsSync(graphPath)) {
  w('_Skipped: `.data/graphify/graphify-out/graph.json` not present._');
  w();
} else {
  const graph = JSON.parse(fs.readFileSync(graphPath, 'utf8'));
  const indexed = new Set((graph.nodes ?? []).map((n) => n.source_file).filter(Boolean));
  w(`Graphify index at commit \`${graph.built_at_commit ?? '(unrecorded)'}\`: `
    + `${(graph.nodes ?? []).length} nodes over ${indexed.size} distinct source files.`);
  w();
  w('| question | evidence files | in the index | missing |');
  w('|---|--:|--:|---|');
  const cover = new Map();
  let totalEv = 0; let totalIn = 0;
  for (const q of questions) {
    const evidence = [...new Set((q.provenance?.evidence ?? []).map((e) => e.split(':')[0]))];
    if (!evidence.length) continue;
    const missing = evidence.filter((f) => !indexed.has(f));
    totalEv += evidence.length; totalIn += evidence.length - missing.length;
    cover.set(q.id, missing.length === 0);
    w(`| ${q.id} | ${evidence.length} | ${evidence.length - missing.length} | `
      + `${missing.map((f) => `\`${f}\``).join(', ') || '—'} |`);
  }
  w();
  w(`**${totalIn}/${totalEv}** ground-truth evidence files are present in the Graphify index. `
    + `**${[...cover.values()].filter((v) => !v).length} of ${cover.size}** questions have at `
    + 'least one required fact the graph cannot see at any price.');
  w();
  w('### Does coverage drive the choice? (no)');
  w();
  const tally = (want) => {
    let g = 0; let t = 0;
    for (const r of B) {
      if (cover.get(r.id) !== want) continue;
      for (const tool of r.tools_executed ?? []) { t += 1; if (isGraphTool(tool)) g += 1; }
    }
    return [g, t];
  };
  const [gf, tf] = tally(true); const [gp, tp] = tally(false);
  w('| questions | graph calls / total calls |');
  w('|---|--:|');
  w(`| ground truth **fully** in the index | ${gf} / ${tf} = ${pct(gf, tf)} |`);
  w(`| ground truth **partially or not** in the index | ${gp} / ${tp} = ${pct(gp, tp)} |`);
  w();
  w('No difference. The agent is not avoiding the graph where the graph is blind — per');
  w('section 4 it commits before it could possibly find out.');
  w();
}

const outPath = path.join(REPO_ROOT, 'docs/benchmarks/coding-v1/analysis/tool-selection-data.md');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, `${out.join('\n')}\n`, 'utf8');
logger.info(`wrote ${path.relative(REPO_ROOT, outPath)} (${out.length} lines)`);
