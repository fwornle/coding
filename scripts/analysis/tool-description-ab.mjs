#!/usr/bin/env node
/**
 * The tool-description A/B: does restating Graphify's MCP tools in applicability-first form
 * change how often an agent reaches for them?
 *
 *   control    coding-v1-r9                  GRAPHIFY_TOOL_DESCRIPTIONS=terse
 *   treatment  coding-v1-abdesc-actionable   GRAPHIFY_TOOL_DESCRIPTIONS=actionable
 *
 * Both are the `hybrid` arm on claude, 16 questions x 3 reps, corpus pinned to the SAME
 * commit (d8a9b0647) via --commit, same model, same continuation budget, same 14-tool
 * surface. The manipulated variable is the `description` string of six MCP tools. Names,
 * input schemas, handlers and returned results are byte-identical between the two.
 *
 * WHAT THIS SCRIPT WILL NOT DO. It will not report a cell-level p-value. 48 cells are 3 reps
 * of 16 questions and the reps are near-perfectly correlated, so the question is the unit of
 * analysis; treating cells as independent is the defect this whole investigation exists to
 * correct (see docs/benchmarks/coding-v1/tool-selection.md, correction 2).
 *
 *   node scripts/analysis/tool-description-ab.mjs
 *   -> docs/benchmarks/coding-v1/analysis/tool-description-ab.md
 */

import fs from 'node:fs';
import path from 'node:path';
import { createLogger } from '../../lib/logging/Logger.js';
import {
  REPO_ROOT, loadRun, byQuestion, cellUsedGraph, isGraphTool,
  fisherExact, mcnemarExact, median, mean,
} from './tool-selection-lib.mjs';

const logger = createLogger('kgbench-analysis', { timestamp: false });
const CONTROL = 'coding-v1-r9';
const TREATMENT = 'coding-v1-abdesc-actionable';

const isGraphify = (t) => t.startsWith('mcp__graphify__');
const isCodegraph = (t) => t.startsWith('mcp__codegraph__');

const A = loadRun(CONTROL, { arm: 'hybrid', agent: 'claude' });
const B = loadRun(TREATMENT, { arm: 'hybrid', agent: 'claude' });

const out = [];
const w = (s = '') => out.push(s);
const pctOf = (a, b) => (b ? `${(100 * a / b).toFixed(2)}%` : 'n/a');

w('# Tool-description A/B — does advertising change uptake?');
w();
w('Generated by `scripts/analysis/tool-description-ab.mjs`. Do not hand-edit.');
w();
w('| | control | treatment |');
w('|---|---|---|');
w(`| run | \`${CONTROL}\` | \`${TREATMENT}\` |`);
w('| `GRAPHIFY_TOOL_DESCRIPTIONS` | `terse` | `actionable` |');
w(`| cells (hybrid / claude) | ${A.length} | ${B.length} |`);
w('| corpus commit | `d8a9b0647` | `d8a9b0647` (pinned) |');
w();

// ── the primary outcome ──────────────────────────────────────────────────────
const tally = (rows) => {
  const t = rows.flatMap((r) => r.tools_executed ?? []);
  return {
    calls: t.length,
    graph: t.filter(isGraphTool).length,
    gfy: t.filter(isGraphify).length,
    cg: t.filter(isCodegraph).length,
    grep: t.filter((x) => x === 'Grep').length,
    read: t.filter((x) => x === 'Read').length,
    glob: t.filter((x) => x === 'Glob').length,
    cellsGfy: rows.filter((r) => (r.tools_executed ?? []).some(isGraphify)).length,
    cellsGraph: rows.filter(cellUsedGraph).length,
  };
};
const a = tally(A); const b = tally(B);

w('## 1. Primary outcome — Graphify uptake');
w();
w('| metric | terse | actionable | change |');
w('|---|--:|--:|---|');
const row = (label, x, y, denomA, denomB) => {
  const extra = denomA ? ` (${pctOf(x, denomA)} → ${pctOf(y, denomB)})` : '';
  const delta = x === 0 ? (y === 0 ? 'no change' : `**0 → ${y}**`) : `${(y / x).toFixed(2)}×`;
  w(`| ${label} | ${x} | ${y} | ${delta}${extra} |`);
};
row('**Graphify calls**', a.gfy, b.gfy, a.calls, b.calls);
row('cells using Graphify', a.cellsGfy, b.cellsGfy);
row('CodeGraph calls', a.cg, b.cg, a.calls, b.calls);
row('all graph calls', a.graph, b.graph, a.calls, b.calls);
row('cells using any graph', a.cellsGraph, b.cellsGraph);
w(`| total tool calls | ${a.calls} | ${b.calls} | — |`);
w(`| \`Grep\` | ${a.grep} | ${b.grep} | ${a.grep ? `${(b.grep / a.grep).toFixed(2)}×` : '—'} |`);
w(`| \`Read\` | ${a.read} | ${b.read} | ${a.read ? `${(b.read / a.read).toFixed(2)}×` : '—'} |`);
w(`| \`Glob\` | ${a.glob} | ${b.glob} | ${a.glob ? `${(b.glob / a.glob).toFixed(2)}×` : '—'} |`);
w();

// ── clustered significance ───────────────────────────────────────────────────
w('## 2. Significance, clustered on the question');
w();
const qGfy = (rows) => {
  const m = new Map();
  for (const r of rows) {
    const hit = (r.tools_executed ?? []).some(isGraphify);
    if (!m.has(r.id)) m.set(r.id, { reps: 0, hits: 0 });
    const e = m.get(r.id); e.reps += 1; if (hit) e.hits += 1;
  }
  return m;
};
const qa = qGfy(A); const qb = qGfy(B);
const ids = [...new Set([...qa.keys(), ...qb.keys()])].sort();
const hitA = ids.filter((i) => (qa.get(i)?.hits ?? 0) > 0).length;
const hitB = ids.filter((i) => (qb.get(i)?.hits ?? 0) > 0).length;
let onlyA = 0; let onlyB = 0;
for (const i of ids) {
  const x = (qa.get(i)?.hits ?? 0) > 0; const y = (qb.get(i)?.hits ?? 0) > 0;
  if (x && !y) onlyA += 1;
  if (!x && y) onlyB += 1;
}
const n = ids.length;
w(`Questions eliciting at least one **Graphify** call: **${hitA}/${n}** terse → **${hitB}/${n}** actionable.`);
w();
w('| test | value |');
w('|---|--:|');
w(`| Fisher exact, two-sided | ${fisherExact(hitB, n - hitB, hitA, n - hitA).toFixed(3)} |`);
w(`| McNemar exact, paired (${onlyB} gained, ${onlyA} lost) | ${mcnemarExact(onlyA, onlyB).toFixed(3)} |`);
w();
w('| question | terse reps w/ Graphify | actionable reps w/ Graphify |');
w('|---|--:|--:|');
for (const i of ids) {
  const x = qa.get(i) ?? { hits: 0, reps: 0 }; const y = qb.get(i) ?? { hits: 0, reps: 0 };
  const mark = (y.hits > 0 && x.hits === 0) ? ' **← new**' : '';
  w(`| ${i} | ${x.hits}/${x.reps} | ${y.hits}/${y.reps}${mark} |`);
}
w();

// ── did the choice move earlier in the cell? ─────────────────────────────────
w('## 3. First tool call — is the change in the opening move?');
w();
w('| first tool | terse | actionable |');
w('|---|--:|--:|');
const firsts = (rows) => {
  const m = new Map();
  for (const r of rows) { const ex = r.tools_executed ?? []; if (ex.length) m.set(ex[0], (m.get(ex[0]) ?? 0) + 1); }
  return m;
};
const fa = firsts(A); const fb = firsts(B);
for (const t of [...new Set([...fa.keys(), ...fb.keys()])].sort()) {
  w(`| \`${t}\` | ${fa.get(t) ?? 0} | ${fb.get(t) ?? 0} |`);
}
w();

// ── did it cost anything? ────────────────────────────────────────────────────
w('## 4. Did it cost correctness, tokens or time?');
w();
w('Scored by the deterministic checklist grader. The judge was disabled for the treatment run');
w('(`--no-judge`): the proxy could not serve the same judge model the control used, and a');
w('judge column graded by a different model is not comparable to one that was not.');
w();
w('> **Latency is NOT comparable between these two runs and is shown for completeness only.**');
w('> The control was measured on an otherwise idle machine; the treatment ran while a');
w('> background consolidator held a second agent process open. kgbench runs its cells strictly');
w('> sequentially precisely because CPU contention corrupts wall-clock — see "When the machine');
w('> lied" in the report. Token counts and tool counts are unaffected by contention; wall');
w('> seconds are. The primary outcome of this A/B is the tool counts in section 1.');
w();
w('| metric | terse | actionable |');
w('|---|--:|--:|');
const stat = (rows, f) => median(rows.map(f).filter((x) => x != null));
w(`| median score | ${stat(A, (r) => r.score).toFixed(2)} | ${stat(B, (r) => r.score).toFixed(2)} |`);
w(`| mean score | ${mean(A.map((r) => r.score ?? 0)).toFixed(3)} | ${mean(B.map((r) => r.score ?? 0)).toFixed(3)} |`);
w(`| cells answered | ${A.filter((r) => r.outcome === 'ok').length}/${A.length} | ${B.filter((r) => r.outcome === 'ok').length}/${B.length} |`);
w(`| median content tokens | ${Math.round(stat(A, (r) => r.content_tokens))} | ${Math.round(stat(B, (r) => r.content_tokens))} |`);
w(`| median wall seconds | ${stat(A, (r) => r.wall_s).toFixed(1)} | ${stat(B, (r) => r.wall_s).toFixed(1)} |`);
w(`| median tool calls | ${stat(A, (r) => r.tool_calls)} | ${stat(B, (r) => r.tool_calls)} |`);
w(`| hallucinations | ${A.filter((r) => r.hallucinated).length} | ${B.filter((r) => r.hallucinated).length} |`);
w();

const outPath = path.join(REPO_ROOT, 'docs/benchmarks/coding-v1/analysis/tool-description-ab.md');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, `${out.join('\n')}\n`, 'utf8');
logger.info(`wrote ${path.relative(REPO_ROOT, outPath)} — Graphify ${a.gfy} → ${b.gfy} calls, ${hitA}/${n} → ${hitB}/${n} questions`);
