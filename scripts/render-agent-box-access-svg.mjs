#!/usr/bin/env node
/**
 * Renders docs-content/images/agent-box-access.svg — every path an agent can
 * read or write, for an agent on the host (greyed: it reaches everything you
 * can) and for an agent in the agent box (each path marked allowed, read-only,
 * box-only, through the guard, not locked yet, or blocked).
 *
 *   node scripts/render-agent-box-access-svg.mjs
 *
 * The ROWS are the source of truth for the picture. They describe what the
 * box ACTUALLY does today (scripts/agent-box.mjs boxRunArgs, the entrypoint,
 * lib/guard/svc.mjs) — verified from inside a box on 2026-11-09, including
 * the gaps. When a gap closes (.planning/guardrail-hardening.md Phase 3),
 * change its row here and re-run; the docs and the overview deck both use
 * the generated file.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(REPO, 'docs-content', 'images', 'agent-box-access.svg');
/** The docs page carries the same rows as a table, between these markers. */
const DOC = path.join(REPO, 'docs-content', 'core-systems', 'agent-box.md');
const START = '<!-- agent-box-access:start (generated by scripts/render-agent-box-access-svg.mjs) -->';
const END = '<!-- agent-box-access:end -->';

/** What the box does with one path. */
export const KINDS = {
  rw:     { color: '#2e7d32', dash: '',      label: 'read-write' },
  ro:     { color: '#1565c0', dash: '',      label: 'read-only' },
  own:    { color: '#00838f', dash: '',      label: "box's own copy" },
  guard:  { color: '#6a1b9a', dash: '7 5',   label: 'through the guard: you approve' },
  login:  { color: '#8d6e63', dash: '9 3 2 3', label: "the agent's own login only" },
  gap:    { color: '#e65100', dash: '3 4',   label: 'reachable: not locked yet' },
  block:  { color: '#c62828', dash: '',      label: 'blocked / not visible' },
};

/** [kind, name, box verdict, detail]. Groups start with a string. */
export const ROWS = [
  'Files and folders',
  ['rw',    'Your project (the workspace)',          'read-write, same path',    'what you launched in; the agent works here in both cases'],
  ['ro',    'The coding repo, when you work elsewhere', 'read-only',             'tools, plugins and extensions the agent runs'],
  ['rw',    'Session transcripts',                   'read-write → session logs', '~/.claude/projects, ~/.copilot/session-state; pi writes into the project'],
  ['own',   'Agent settings and logins',             'its own, not yours',       'host: ~/.claude, ~/.copilot, Keychain · box: own login in a volume; pi gets a copy'],
  ['block', 'The rest of your home folder',          'not visible',              'other repos, ~/.ssh, cloud credentials, ~/.coding data, shell config'],
  ['ro',    'The guard: hooks, rules, hook settings', 'root-owned, read-only',   'on the host the agent can edit them, or switch its hooks off'],
  ['block', 'Guard keys and audit log',              'public key only',          '~/.coding/guard: signing key, approver token, hash-chained audit'],
  'Containers and processes',
  ['block', 'Docker socket',                         'no socket',                'host: start, stop, rebuild any container, mount any folder'],
  ['guard', 'coding containers',                     'via coding svc',           'box: status, logs, restart, graphify; up / rebuild need your approval'],
  ['block', 'Host processes and daemons',            'not visible',              'host: kill, launchctl / systemctl, restart services'],
  ['block', 'MCP servers, knowledge injection',      'not loaded',               'loaded for the host agent only'],
  'Network',
  ['rw',    'LLM proxy  :12435',                     'every model call',         'routed, metered and logged; from the box through the network gate'],
  ['guard', 'Guard daemon  :3035',                   'can ask, never approve',   'override requests and coding svc; approving needs your factor'],
  ['ro',    'Health coordinator  :3034',             'GET /health/state only',   'the health line on each prompt; every other route refused at the gate'],
  ['block', 'Other host services',                   'refused at the gate',      'obs-api :12436, dashboard :3032, Qdrant :6333, MCP servers …'],
  ['login', 'Internet',                              'login hosts only',         'e.g. platform.claude.com for claude; every refusal is reported'],
  'You and your accounts',
  ['rw',    'Your terminal',                         'keys, screen, paste',      'tmux pane; Cmd+V image paste goes through a bridge'],
  ['guard', 'Overriding a rule',                     'only grants you sign',     'host: one line in the transcript, which the agent can type itself'],
  ['guard', 'git push / fetch, gh',                  'via the guard',            'pinned remotes only, no force or delete; gh reads free, PR writes need you'],
];

const FOOTNOTE = [
  'Box network: an internal Docker network; its gate forwards the LLM proxy and the guard, and relays GET /health/state. CODING_BOX_NETWORK=open lifts it (recorded).',
  'Planned (Phase 3): result-check state out of the agent’s reach.',
  'Default: claude, copilot and pi run in the box; opencode with --box. --no-box runs on the host and is recorded in the guard audit log.',
];

/** The kinds some row uses, in KINDS order — the legend shows only these. */
function usedKinds() {
  const used = new Set(ROWS.filter((r) => typeof r !== 'string').map((r) => r[0]));
  return Object.entries(KINDS).filter(([k]) => used.has(k));
}

// ---------------------------------------------------------------- layout

const W = 1320;
const FONT = "Inter, -apple-system, 'Segoe UI', Helvetica, Arial, sans-serif";
const CARD_X = 330, CARD_W = 600, CARD_H = 46, GAP = 6, HEAD_H = 30;
const WALL_X = 1010, BOX_R = 1296;
const TOP = 160;

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

export function render() {
  const parts = []; // group headings, emitted after the background
  const rowsY = [];
  let y = TOP;
  for (const r of ROWS) {
    if (typeof r === 'string') {
      parts.push(`<text x="${CARD_X}" y="${y + 20}" font-size="12" font-weight="700" fill="#5f6b7a">${esc(r.toUpperCase().split('').join('\u2009'))}</text>`);
      y += HEAD_H;
      continue;
    }
    rowsY.push({ r, y });
    y += CARD_H + GAP;
  }
  const bottom = y - GAP;
  const midY = (TOP + bottom) / 2;
  const H = bottom + 30 + FOOTNOTE.length * 20 + 20;

  const out = [];
  out.push(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" font-family="${FONT}" role="img" aria-labelledby="t d">`);
  out.push('<title id="t">What an agent can reach: on the host versus in the agent box</title>');
  out.push(`<desc id="d">Every path an agent can read or write. The host agent (grey) reaches all of them. The agent in the box: ${esc(rowsY.map(({ r }) => `${r[1]}: ${r[2]}`).join('; '))}.</desc>`);
  out.push(`<rect x="0" y="0" width="${W}" height="${H}" rx="18" fill="#ffffff"/>`);
  out.push(...parts); // group headings

  // title + legend
  out.push(`<text x="30" y="44" font-size="26" font-weight="700" fill="#1b2430">What an agent can reach</text>`);
  out.push(`<text x="30" y="72" font-size="15" fill="#5f6b7a">Grey: an agent on the host reaches everything you can. Colour: what the same agent reaches from inside the agent box.</text>`);
  let lx = 30;
  let ly = 104;
  out.push(`<line x1="${lx}" y1="${ly}" x2="${lx + 34}" y2="${ly}" stroke="#b9bec5" stroke-width="3"/><text x="${lx + 42}" y="${ly + 5}" font-size="13" fill="#8a929c">host agent: everything</text>`);
  lx += 210;
  for (const [k, v] of usedKinds()) {
    const itemW = 42 + v.label.length * 7.6 + 26;
    if (lx + itemW > W - 20) { lx = 30; ly += 26; }
    if (k === 'block') {
      out.push(`<line x1="${lx}" y1="${ly}" x2="${lx + 18}" y2="${ly}" stroke="${v.color}" stroke-width="3"/>${cross(lx + 27, ly, v.color)}`);
    } else {
      out.push(`<line x1="${lx}" y1="${ly}" x2="${lx + 34}" y2="${ly}" stroke="${v.color}" stroke-width="3" ${v.dash ? `stroke-dasharray="${v.dash}"` : ''}/>`);
    }
    out.push(`<text x="${lx + 42}" y="${ly + 5}" font-size="13" fill="#3a4450">${esc(v.label)}</text>`);
    lx += itemW;
  }

  // host agent (greyed) and its fan to every path
  const HX = 30, HW = 210, HH = 110;
  for (const { y: ry } of rowsY) {
    const cy = ry + CARD_H / 2;
    out.push(`<path d="M ${HX + HW} ${midY} C ${HX + HW + 50} ${midY}, ${CARD_X - 50} ${cy}, ${CARD_X} ${cy}" fill="none" stroke="#c9cdd2" stroke-width="1.6"/>`);
  }
  out.push(`<rect x="${HX}" y="${midY - HH / 2}" width="${HW}" height="${HH}" rx="14" fill="#f2f3f5" stroke="#c9cdd2" stroke-width="2"/>`);
  out.push(`<text x="${HX + HW / 2}" y="${midY - 14}" text-anchor="middle" font-size="17" font-weight="700" fill="#8a929c">Agent on the host</text>`);
  out.push(`<text x="${HX + HW / 2}" y="${midY + 10}" text-anchor="middle" font-size="12.5" fill="#9aa1aa">runs as you</text>`);
  out.push(`<text x="${HX + HW / 2}" y="${midY + 28}" text-anchor="middle" font-size="12.5" fill="#9aa1aa">--no-box, or opencode</text>`);

  // the box
  const AX = WALL_X + 70, AW = BOX_R - AX - 20, AH = 128;
  out.push(`<rect x="${WALL_X}" y="${TOP - 6}" width="${BOX_R - WALL_X}" height="${bottom - TOP + 12}" rx="16" fill="#eef4fc" stroke="#1565c0" stroke-width="3"/>`);
  out.push(`<text x="${(WALL_X + BOX_R) / 2}" y="${TOP + 22}" text-anchor="middle" font-size="15" font-weight="700" fill="#1565c0">agent box</text>`);
  out.push(`<text x="${(WALL_X + BOX_R) / 2}" y="${TOP + 42}" text-anchor="middle" font-size="12" fill="#3a4f6b">Linux container · your uid, not root</text>`);
  out.push(`<text x="${(WALL_X + BOX_R) / 2}" y="${TOP + 58}" text-anchor="middle" font-size="12" fill="#3a4f6b">no_new_privs · no Docker socket</text>`);
  out.push(`<text x="${(WALL_X + BOX_R) / 2}" y="${TOP + 74}" text-anchor="middle" font-size="12" fill="#3a4f6b">network: gate only</text>`);

  // cards, connectors, inner fan
  for (const { r: [kind, name, verdict, detail], y: ry } of rowsY) {
    const k = KINDS[kind];
    const cy = ry + CARD_H / 2;
    out.push(`<rect x="${CARD_X}" y="${ry}" width="${CARD_W}" height="${CARD_H}" rx="9" fill="#ffffff" stroke="#d5d9de" stroke-width="1.2"/>`);
    out.push(`<rect x="${CARD_X + CARD_W - 6}" y="${ry}" width="6" height="${CARD_H}" rx="3" fill="${k.color}"/>`);
    out.push(`<text x="${CARD_X + 14}" y="${ry + 20}" font-size="14.5" font-weight="700" fill="#1b2430">${esc(name)}</text>`);
    out.push(`<text x="${CARD_X + CARD_W - 16}" y="${ry + 20}" text-anchor="end" font-size="13.5" font-weight="700" fill="${k.color}">${esc(verdict)}</text>`);
    out.push(`<text x="${CARD_X + 14}" y="${ry + 38}" font-size="12" fill="#7a838d">${esc(detail)}</text>`);
    const x0 = CARD_X + CARD_W;
    if (kind === 'block') {
      out.push(`<line x1="${x0}" y1="${cy}" x2="${x0 + 30}" y2="${cy}" stroke="${k.color}" stroke-width="2.6"/>`);
      out.push(cross(x0 + 42, cy, k.color));
      continue;
    }
    const dash = k.dash ? `stroke-dasharray="${k.dash}"` : '';
    out.push(`<line x1="${x0}" y1="${cy}" x2="${WALL_X}" y2="${cy}" stroke="${k.color}" stroke-width="2.6" ${dash}/>`);
    if (kind === 'guard') out.push(gate(x0 + 40, cy, k.color));
    out.push(`<path d="M ${WALL_X} ${cy} C ${WALL_X + 40} ${cy}, ${AX - 40} ${midY}, ${AX} ${midY}" fill="none" stroke="${k.color}" stroke-width="2" ${dash} opacity="0.85"/>`);
  }
  out.push(`<rect x="${AX}" y="${midY - AH / 2}" width="${AW}" height="${AH}" rx="14" fill="#1565c0"/>`);
  out.push(`<text x="${AX + AW / 2}" y="${midY - 22}" text-anchor="middle" font-size="17" font-weight="700" fill="#ffffff">Agent in the box</text>`);
  out.push(`<text x="${AX + AW / 2}" y="${midY + 4}" text-anchor="middle" font-size="12.5" fill="#dbe8fb">claude · copilot · pi</text>`);
  out.push(`<text x="${AX + AW / 2}" y="${midY + 22}" text-anchor="middle" font-size="12.5" fill="#dbe8fb">by default</text>`);
  out.push(`<text x="${AX + AW / 2}" y="${midY + 40}" text-anchor="middle" font-size="12.5" fill="#dbe8fb">opencode with --box</text>`);

  let fy = bottom + 34;
  for (const line of FOOTNOTE) {
    out.push(`<text x="30" y="${fy}" font-size="13" fill="#5f6b7a">${esc(line)}</text>`);
    fy += 20;
  }
  out.push('</svg>');
  return out.join('\n') + '\n';
}

function cross(x, y, color) {
  const s = 7;
  return `<g stroke="${color}" stroke-width="3.2" stroke-linecap="round"><line x1="${x - s}" y1="${y - s}" x2="${x + s}" y2="${y + s}"/><line x1="${x - s}" y1="${y + s}" x2="${x + s}" y2="${y - s}"/></g>`;
}

/** The guard on a path: a small shield-like diamond. */
function gate(x, y, color) {
  return `<g><rect x="${x - 9}" y="${y - 9}" width="18" height="18" transform="rotate(45 ${x} ${y})" fill="#ffffff" stroke="${color}" stroke-width="2.4"/><circle cx="${x}" cy="${y}" r="3" fill="${color}"/></g>`;
}

const MARK = { rw: '✅', ro: '👁️', own: '📦', guard: '🔐', login: '🔑', gap: '⚠️', block: '⛔' };

/** The same rows as a Markdown table (docs page, between START and END). */
export function table() {
  const lines = ['| | Path | In the box | Detail |', '|---|---|---|---|'];
  for (const r of ROWS) {
    if (typeof r === 'string') { lines.push(`| | **${r}** | | |`); continue; }
    const [kind, name, verdict, detail] = r;
    lines.push(`| ${MARK[kind]} | ${name.replace(/\s+/g, ' ')} | ${verdict} | ${detail.replace(/\|/g, '\\|')} |`);
  }
  lines.push('', `${usedKinds().map(([k, v]) => `${MARK[k]} ${v.label}`).join(' · ')}. On the host, the agent has every one of these.`);
  return lines.join('\n');
}

export function withTable(doc) {
  const a = doc.indexOf(START);
  const b = doc.indexOf(END);
  if (a === -1 || b === -1 || b < a) throw new Error(`${path.relative(REPO, DOC)}: markers ${START} … ${END} not found`);
  return `${doc.slice(0, a + START.length)}\n${table()}\n${doc.slice(b)}`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(OUT, render());
  fs.writeFileSync(DOC, withTable(fs.readFileSync(DOC, 'utf8')));
  process.stdout.write(`wrote ${path.relative(REPO, OUT)} and the table in ${path.relative(REPO, DOC)}\n`);
}
