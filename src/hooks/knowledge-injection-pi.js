#!/usr/bin/env node

/**
 * Knowledge Injection Adapter for pi (session-start)
 * Called once at session start by launch-agent-common.sh.
 *
 * Channel: pi's own AGENTS.md discovery. pi loads AGENTS.md from its config
 * directory, from parent directories, and from the working directory — verified
 * live, with the negative control that `pi -nc` (context-file discovery off)
 * stops seeing the same content.
 *
 * We write into the CONFIG directory, never the project. The project's own
 * AGENTS.md (and CLAUDE.md, which pi also reads) belong to the repository and
 * are frequently version-controlled; injecting retrieved knowledge into either
 * would be an unannounced edit of a user-owned file, and would show up in their
 * `git status`. The config dir is ours by construction — config/agents/pi.sh
 * points PI_CODING_AGENT_DIR at <repo>/.pi-agent for wrapper-scoped launches.
 *
 * That ownership is exactly why this refuses to run when the config dir is the
 * user's default ~/.pi/agent (a `CODING_AGENT_SCOPE=global` install): there,
 * AGENTS.md is the user's own global instruction file for every pi session on
 * the machine, and overwriting it would silently destroy their configuration.
 */

import { callRetrieval } from './retrieval-client.js';
import { execSync } from 'node:child_process';
import { writeFileSync, mkdirSync } from 'node:fs';
import { homedir } from 'node:os';
import { resolve, join, basename } from 'node:path';

const cwd = process.env.CODING_PROJECT_DIR || process.env.TARGET_PROJECT_DIR || process.cwd();
const project = basename(cwd);

/**
 * The file to write, or null when writing would clobber something we don't own.
 */
function resolveTargetFile() {
  const cfgDir = process.env.PI_CODING_AGENT_DIR;
  if (!cfgDir) {
    // pi.sh always exports this. Absent means we are not running under the
    // launcher, so we have no directory we can claim as ours.
    process.stderr.write('[knowledge-pi] PI_CODING_AGENT_DIR unset -- skipping injection\n');
    return null;
  }
  const defaultDir = join(homedir(), '.pi', 'agent');
  if (resolve(cfgDir) === resolve(defaultDir)) {
    process.stderr.write(
      `[knowledge-pi] config dir is pi's default (${defaultDir}) -- refusing to overwrite the user's own AGENTS.md\n`,
    );
    return null;
  }
  return join(cfgDir, 'AGENTS.md');
}

async function main() {
  try {
    const targetFile = resolveTargetFile();
    if (!targetFile) return;

    // Gather recent files from git for context (D-08)
    let recentFiles = [];
    try {
      const output = execSync('git diff --name-only HEAD~3 2>/dev/null', { cwd, encoding: 'utf8', timeout: 3000 });
      recentFiles = output.trim().split('\n').filter(Boolean).slice(0, 20);
    } catch { /* no git or no commits -- skip */ }

    const result = await callRetrieval({
      // In an experiment cell the runner sets CODING_EXPERIMENT_GOAL to the task; retrieve on that
      // real task (so the IDF pass + LLM judge have a task to judge against) instead of the generic
      // project-context query used for interactive session-start injection.
      query: process.env.CODING_EXPERIMENT_GOAL || `project context for ${project}`,
      budget: 1000,
      threshold: 0.65,
      context: { project, cwd, recent_files: recentFiles, agent: 'pi' },
      // Experiment cells signal themselves via CODING_EXPERIMENT_TASK_ID (composite id, contains
      // '--') so the retrieval service suppresses the Working Memory scaffold + restricts to
      // curated tiers. Null for interactive sessions (no experiment gate).
      task_id: process.env.CODING_EXPERIMENT_TASK_ID || process.env.TASK_ID || null,
      timeout: 3000,
    });

    if (!result || !result.markdown || result.meta?.results_count === 0) {
      return; // No relevant knowledge -- skip writing
    }

    mkdirSync(targetFile.replace(/\/[^/]+$/, ''), { recursive: true });

    const header = `<!-- Auto-generated by coding knowledge injection - ${new Date().toISOString()} -->\n`;
    const content = header + `# Knowledge Context for ${project}\n\n${result.markdown}\n`;
    writeFileSync(targetFile, content, 'utf8');

    process.stderr.write(`[knowledge-pi] Wrote ${content.length} chars to ${targetFile}\n`);
  } catch (err) {
    process.stderr.write(`[knowledge-pi] Error: ${err.message}\n`);
    // Fail-open: exit 0 regardless
  }
}

main().then(() => process.exit(0));
